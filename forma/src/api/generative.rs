/// A tool for the LLM to use.
#[derive(Serialize, Deserialize, Debug)]
pub struct SimplifiedTool {
    /// The name of the tool. Should be descriptive so the LLM can tell it
    /// apart from other tools.
    pub name: String,
    /// A more detailed description of what the tool does.
    pub description: String,
    /// The action that runs when this tool is selected.
    pub tool: SimplifiedToolRunner,
}

impl OpenAPIJsonSchema for SimplifiedTool {
    fn schema_name() -> Cow<'static, str> {
        "tool".into()
    }
    fn schema_id() -> Cow<'static, str> {
        "tool".into()
    }
    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        let tool_runner: Schema = schema_for!(SimplifiedToolRunner);

        json_schema!({
          "description": "A tool for the LLM to use.",
          "type": "object",
          "properties": {
            "name": {
              "description": "The name of the tool. Should be descriptive so the LLM can tell it\napart from other tools.",
              "type": "string"
            },
            "description": {
              "description": "A more detailed description of what the tool does.",
              "type": "string"
            },
            "tool": tool_runner
          },
          "required": [
            "name",
            "description",
            "tool"
          ]
        })
    }
}

/// The bundle a generated tool should carry, so clients can render it with a
/// dedicated widget. Mirrors `TOOL_BUNDLES` in the web editor
/// (`front/src/lib/workflow.ts`): MCP servers are bundled by URL, which is what
/// clients key the provider logo on.
fn tool_bundle(tool: &ToolRunnerDefinition) -> Option<String> {
    match tool {
        ToolRunnerDefinition::TavilySearch(_) => Some("web-search".to_string()),
        ToolRunnerDefinition::Fetch(_) => Some("curl".to_string()),
        ToolRunnerDefinition::Mailgun(_) => Some("send-email".to_string()),
        ToolRunnerDefinition::GoogleKnowledgebase(_) => Some("workspace".to_string()),
        ToolRunnerDefinition::Scrapbook(_) => Some("scrapbook".to_string()),
        ToolRunnerDefinition::Mcp(mcp) => Some(mcp.url.clone()),
        _ => None,
    }
}

impl From<SimplifiedTool> for ToolDefinition {
    fn from(value: SimplifiedTool) -> Self {
        let tool: ToolRunnerDefinition = value.tool.into();
        ToolDefinition {
            name: sanitize_string(&value.name),
            description: Some(value.description),
            bundle: tool_bundle(&tool),
            tool,
            ..Default::default()
        }
    }
}

/// A node is a step in the Directed Acyclic Graph (DAG) that make up an agent
///
/// A node always triages (using the system prompt, tools and LLM Client);
/// then calls the tools (if any); then summarises the results using the LLM
/// client, the summarization_prompt (if any) or the system prompt again
#[derive(Serialize, Deserialize, Debug)]
pub struct SimplifiedNode {
    /// The ID of the node. It is referenced by other nodes (through
    /// `{{id}}` placeholders in their prompts) to consume this node's
    /// output.
    pub id: String,
    /// The main instruction given to the LLM. It can reference the output
    /// of other nodes with `{{other_node_id}}` placeholders.
    pub system_prompt: String,
    /// The tools the LLM can decide to call.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tools: Vec<SimplifiedTool>,
    /// The prompt used to summarise the results of this node. The
    /// value will be ignored if no tools are available.
    pub summarization_prompt: String,
}

impl OpenAPIJsonSchema for SimplifiedNode {
    fn schema_name() -> Cow<'static, str> {
        "node".into()
    }
    fn schema_id() -> Cow<'static, str> {
        "node".into()
    }
    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        let tool: Schema = schema_for!(SimplifiedTool);

        json_schema!({
          "description": "A node is a step in the Directed Acyclic Graph (DAG) that make up an agent\n\nA node always triages (using the system prompt, tools and LLM Client);\nthen calls the tools (if any); then summarises the results using the LLM\nclient, the summarization_prompt (if any) or the system prompt again",
          "type": "object",
          "properties": {
            "id": {
              "description": "The ID of the node. It is referenced by other nodes (through\n`{{id}}` placeholders in their prompts) to consume this node's\noutput.",
              "type": "string"
            },
            "system_prompt": {
              "description": "The main instruction given to the LLM. It can reference the output\nof other nodes with `{{other_node_id}}` placeholders.",
              "type": "string"
            },
            "tools": {
              "description": "The tools the LLM can decide to call.",
              "type": "array",
              "items": tool
            },
            "summarization_prompt": {
              "description": "The prompt used to summarise the results of this node. The\nvalue will be ignored if no tools are available.",
              "type": "string"
            }
          },
          "required": [
            "id",
            "system_prompt",
            "summarization_prompt"
          ]
        })
    }
}

impl SimplifiedNode {
    /// Converts this simplified node into a full [`NodeDefinition`].
    pub(crate) fn into_definition(self) -> Result<NodeDefinition, FormaError> {
        let tools = self
            .tools
            .into_iter()
            .map(|t| TemplateField::Object(t.into()))
            .collect();

        let llm = GenaiClient::VertexAi(VertexAI::default());
        Ok(NodeDefinition {
            id: self.id,
            llm,
            stream: true, // by default, we stream
            system_prompt: self.system_prompt,
            summarization_prompt: Some(self.summarization_prompt),
            tools,
            ..Default::default()
        })
    }
}

/// A Workflow is a set of nodes plus the description of what it
/// outputs. The id is generated and evaluations are omitted.
///
/// All nodes that are required to calculate the output will be ran.
#[derive(Serialize, Deserialize, Debug)]
pub struct SimplifiedWorkflow {
    /// The nodes that make up the workflow. They form a dependency graph
    /// through the `{{node_id}}` placeholders used in their prompts.
    pub node: SimplifiedNode,
}

impl OpenAPIJsonSchema for SimplifiedWorkflow {
    fn schema_name() -> Cow<'static, str> {
        "workflow".into()
    }
    fn schema_id() -> Cow<'static, str> {
        "workflow".into()
    }
    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        let node: Schema = schema_for!(SimplifiedNode);
        json_schema!({
            "description": "A Workflow is a set of nodes plus the description of what it\noutputs. The id is generated and evaluations are omitted.\n\nAll nodes that are required to calculate the output will be ran.",
            "type": "object",
            "properties": {
                "node": node
            },
            "required": ["node"]
        })
    }
}

impl SimplifiedWorkflow {
    /// Converts this simplified workflow into a full [`WorkflowDefinition`].
    pub(crate) fn into_definition(self) -> Result<WorkflowDefinition, FormaError> {
        let node_id = self.node.id.to_string();
        let nodes = vec![self.node.into_definition()?];

        Ok(WorkflowDefinition {
            nodes,
            output: Some(WorkflowOutput::Text(node_id)),
            ..Default::default()
        })
    }
}

/// An AI Agent is defined as a starting workflow, which triggers
/// the execution of a series of nodes to produce an output.
///
/// The Name and Description are meant to let the users search for agents in the
/// website, but do not change the agent's behavior.
///
/// Agents are composed of four elements:
/// 1. A starting workflow
/// 2. Workflows are Directed Acyclic Graphs (DAGs) that define the agent's behavior.
/// 3. A node within the workflow defines a single step in the agent's behavior. All nodes required to calculate the Workflow output are ran
/// 4. Each node always does the following: (1) triages its input, deciding whether to call tools; (2) calls tools; (3) summarises
#[derive(Serialize, Deserialize, Debug)]
pub struct SimplifiedAgentDefinition {
    /// The name of the agent.
    pub name: String,
    /// A description of the agent, used for searching purposes.
    pub description: String,
    /// The workflow that serves as the starting point of this agent.
    pub start: SimplifiedWorkflow,

    /// A set of input variables that can then be referenced
    /// in system prompts in nodes of the agent
    pub variables: Vec<InputVariable>,

    /// Examples of what a user could ask the agent first.
    #[serde(default)]
    pub suggestions: Vec<String>,
}

impl SimplifiedAgentDefinition {
    /// Converts this simplified definition into a full [`AgentDefinition`],
    /// generating an id and leaving the evaluations empty.
    pub fn into_definition(self) -> Result<AgentDefinition, FormaError> {
        let variables = self
            .variables
            .into_iter()
            .map(|x| InputVariable {
                name: sanitize_string(&x.name),
                type_: x.type_,
                value: x.value,
                placeholder: x.placeholder,
            })
            .collect();
        Ok(AgentDefinition {
            id: default_agent_id(),
            name: self.name,
            description: self.description,
            start: self.start.into_definition()?,
            variables,
            suggestions: self.suggestions,
            ..Default::default()
        })
    }
}

