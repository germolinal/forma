//! Simplified, LLM-friendly mirrors of the full Forma definitions.
//!
//! The full [`AgentDefinition`] tree is rich: it carries evaluations, LLM
//! sampling parameters, summarisation prompts, output schemas and several
//! advanced tool variants. Asking an LLM to produce one of those directly is
//! error prone and dilutes its attention with details a human is better placed
//! to tune.
//!
//! The types in this module describe the *shape* of an agent at a high level —
//! enough for an LLM to lay out the workflow, nodes, prompts and tools — while
//! deliberately omitting everything that should be refined by a human
//! afterwards. None of the simplified types carry evaluations, and the
//! simplified LLM client exposes only the provider and the model (no
//! temperature, penalties, token limits, …).
//!
//! Each simplified type derives [`schemars::JsonSchema`] (under the `api`
//! feature) so a JSON Schema can be generated and handed to an LLM, and offers
//! a conversion into its full counterpart that fills every omitted field with
//! its default. `schemars` lives only in this crate: the simplified types are
//! self-contained and convert into the inner-crate types (such as
//! [`GenaiClient`]) through a serde round-trip, so `genai_client` and friends
//! never gain a `schemars` dependency.

