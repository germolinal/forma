fn sanitize_string(s: &str) -> String {
    s.trim()
        .to_lowercase()
        .chars()
        .map(|c| match c {
            'á' | 'à' | 'â' | 'ä' | 'ã' => 'a',
            'é' | 'è' | 'ê' | 'ë' => 'e',
            'í' | 'ì' | 'î' | 'ï' => 'i',
            'ó' | 'ò' | 'ô' | 'ö' | 'õ' => 'o',
            'ú' | 'ù' | 'û' | 'ü' => 'u',
            'ñ' => 'n',
            'ç' => 'c',
            ' ' => '_',
            other => other,
        })
        .collect()
}

/// Details about the tool to run
#[derive(Serialize, Deserialize, Debug)]
#[serde(rename_all = "kebab-case")]
pub enum SimplifiedToolRunner {
    /// Picks one of several templates and asks the LLM to fill its fields.
    /// Useful for canned, non-robotic responses. Use the
    /// `{{name: type "description"}}` syntax for fields.
    Template,
    // /// Generates exposes a Workflow as a tool, allowing for
    // /// complex composability
    // Workflow {
    //     /// The workflow to expose as a tool.
    //     workflow: SimplifiedWorkflow,
    //     /// Determines the template for the message that will be used
    //     /// to trigger this workflow execution as a tool. The fields
    //     /// required will be generated by the LLM of the node that
    //     /// decides to call this tool.
    //     input_prompt: String,
    // },
    // /// Makes an HTTP REST API call. Path parameters are declared inline in
    // /// the `url` using the `{{name: type "description"}}` syntax. A request
    // /// body schema (if any) is to be configured later
    // ApiCall,
    /// Connects to the Hubspot API.
    HubspotMcp,
    /// Connects to a custom MCP server.
    CustomMcp,
    /// A tool for sending emails
    SendEmail,
    /// Searches the web
    WebSearch,
    /// Fetches the contents of a URL
    FetchWebsite,
    /// Generates an image
    GenImage,
}

impl OpenAPIJsonSchema for SimplifiedToolRunner {
    fn schema_name() -> Cow<'static, str> {
        "tool-runner".into()
    }
    fn schema_id() -> Cow<'static, str> {
        "tool-runner".into()
    }
    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        json_schema!({
          "description": "Details about the tool to run. Note that MCP tools are a bundle of many tools; never add an MCP tool twice as it will duplicate and later fail",
          "type": "string",
          "enum": [
            "template",
            "hubspot-mcp",
            "custom-mcp",
            "send-email",
            "web-search",
            "fetch-website"
          ]
        })
    }
}

